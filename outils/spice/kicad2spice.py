def num(v):
    v = v.split()[0].replace('µ', 'u')
    m = re.match(r'^(\d+)([pnumkKM])(\d+)$', v)        # 4k99, 7k15, 2u2
    if m: return m.group(1) + '.' + m.group(3) + {'K': 'k', 'M': 'Meg', 'k': 'k'}.get(m.group(2), m.group(2))
    m = re.match(r'^([\d.]+)([pnumkKM]?)', v)
    return m.group(1) + {'K': 'k', 'M': 'Meg', 'k': 'k', '': ''}.get(m.group(2), m.group(2))

def val(v):
    s = num(v); m = re.match(r'([\d.]+)(.*)', s)
    return float(m.group(1)) * {'': 1, 'p': 1e-12, 'n': 1e-9, 'u': 1e-6, 'm': 1e-3, 'k': 1e3, 'Meg': 1e6}[m.group(2)]

def block(s, i):
    d = 0
    for k in range(i, len(s)):
        if s[k] == '(': d += 1
        elif s[k] == ')':
            d -= 1
            if d == 0: return s[i:k + 1]

def load(pcb, sch):
    P = open(pcb).read(); S = open(sch).read()
    lib = dict((r, l) for l, r in re.findall(r'\(symbol\s*\(lib_id "([^"]+)"\).*?\(property "Reference" "([^"]+)"', S, re.S))
    parts = {}
    for m in re.finditer(r'\(footprint "', P):
        b = block(P, m.start())
        ref = re.search(r'\(property "Reference" "([^"]+)"', b).group(1)
        value = re.search(r'\(property "Value" "([^"]+)"', b).group(1)
        pads = {}
        for pb in re.finditer(r'\(pad "([^"]*)"', b):
            pbk = block(b, pb.start()); nm = re.search(r'\(net \d+ "([^"]*)"\)', pbk)
            if nm and pb.group(1): pads.setdefault(pb.group(1), nm.group(1))
        parts[ref] = dict(value=value, pads=pads, lib=lib.get(ref, '').split(':')[-1])
    return parts

def node(n):
    if n in ('GND', ''): return '0'
    return re.sub(r'[^A-Za-z0-9_]', '_', n.replace('+', 'P').replace('-', 'M'))

def netlist(parts, cfg):
    L = ['* generated by outils/spice/kicad2spice.py', MODELS]
    pots, rot, spdt, drive, skip = cfg.get('pots', {}), cfg.get('rot', {}), cfg.get('spdt', {}), cfg.get('drive', {}), set(cfg.get('skip', []))
    for ref, p in sorted(parts.items()):
        if ref in skip: continue
        t, v, n = p['lib'], p['value'], {k: node(x) for k, x in p['pads'].items()}
        g = lambda k: n.get(k, 'NC_%s_%s' % (ref, k))
        if t == 'R': L.append(f"R{ref} {g('1')} {g('2')} {num(v)}")
        elif t == 'C': L.append(f"C{ref} {g('1')} {g('2')} {num(v)}")
        elif t == 'D':
            m = 'DZ5V1' if 'BZT' in v else 'DSS14' if 'SS1' in v else 'D1N4148'
            L.append(f"D{ref} {g('2')} {g('1')} {m}")
        elif t == 'NPN':
            if 'J11' in v: L.append(f"J{ref} {g('1')} {g('3')} {g('2')} J112")
            else: L.append(f"Q{ref} {g('3')} {g('1')} {g('2')} BC847")
        elif t == 'DUALNPN':
            L.append(f"Q{ref}a {g('6')} {g('2')} {g('1')} BC847"); L.append(f"Q{ref}b {g('3')} {g('5')} {g('4')} BC847")
        elif t in ('TL074', 'TL072'):
            units = [('3', '2', '1'), ('5', '6', '7')] + ([('10', '9', '8'), ('12', '13', '14')] if t == 'TL074' else [])
            vp, vn = (g('4'), g('11')) if t == 'TL074' else (g('8'), g('4'))
            for k, (a, b, o) in enumerate(units):
                L.append(f"X{ref}{'ABCD'[k]} {g(a)} {g(b)} {g(o)} {vp} {vn} TL07X")
        elif t == 'LM13700':
            for k, (a, b, c, d, bi, bo, o) in enumerate([('3', '4', '1', '2', '7', '8', '5'), ('14', '13', '16', '15', '10', '9', '12')]):
                L.append(f"X{ref}{k + 1} {g(a)} {g(b)} {g(c)} {g(d)} {g(bi)} {g(bo)} {g(o)} {g('11')} {g('6')} LM13700H")
        elif t in ('POT', 'TRIM'):
            R = val(v); x = min(max(pots.get(ref, 0.5), 0.001), 0.999)
            L.append(f"R{ref}a {g('1')} {g('2')} {R * x:.6g}"); L.append(f"R{ref}b {g('2')} {g('3')} {R * (1 - x):.6g}")
        elif t == 'JACK':
            if ref in drive: L.append(f"V{ref} {g('T')} 0 {drive[ref]}")
            elif 'TN' in n and n['TN'] != g('T'): L.append(f"R{ref}sw {g('T')} {g('TN')} 0.01")
            L.append(f"R{ref}load {g('T')} 0 100k")
        elif t == 'SPDT': L.append(f"R{ref}sw {g('2')} {g(spdt.get(ref, '1'))} 0.01")
        elif t == 'ROT12': L.append(f"R{ref}sw {g('C')} {g(rot.get(ref, '1'))} 0.01")
        elif t == 'EURO10':
            # supplies ramp up in 1 ms from 0 V (start the simulation with "uic") : like a real power-on, oscillators start by themselves
            L.append(f"V{ref}m {g('1')} 0 PWL(0 0 1m -12)"); L.append(f"V{ref}p {g('10')} 0 PWL(0 0 1m 12)")
        else: L.append(f"* {ref} ({t} {v}) not simulated")
    L.append(cfg.get('extra', ''))
    L.append(cfg.get('tran', '.tran 1u 10m'))
    L.append('.options method=gear reltol=1e-4 abstol=1e-11 vntol=1e-6 itl4=200')
    L.append('.end')
    return '\n'.join(L)

if __name__ == '__main__':
    parts = load(sys.argv[1], sys.argv[2])
    cfg = json.load(open(sys.argv[4])) if len(sys.argv) > 4 else {}
    open(sys.argv[3], 'w').write(netlist(parts, cfg))
    print(len(parts), 'parts ->', sys.argv[3])
